export const getRandomFace = () => faces[Math.floor(Math.random() * faces.length)]

export const getRandomColor = (seed, hue) => {
	const encode = string => {
		if (!string) return seed
		string = `${string}`
		let number = "0x"
		const length = string.length
		for (let i = 0; i < length; i++)
			number += string.charCodeAt(i).toString(16)
		return number
	}
	const formattedSeed = encode(seed)
	const getRandomIndex = len => Math.floor(formattedSeed ? formattedSeed % len : Math.random() * len)

	let selectedHue = colors[hue]
	if (!selectedHue) {
		const arrColors = Object.values(colors)
		selectedHue = arrColors[getRandomIndex(arrColors.length)]
	}
	return selectedHue[getRandomIndex(selectedHue.length)]
}